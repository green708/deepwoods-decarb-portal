// Turns a phpMyAdmin export of the OLD database into a data-only import file for the v2 database.
//
//   node scripts/make-import-from-dump.mjs <old-export.sql> [out.sql]
//
// Keeps every row, every id and every AUTO_INCREMENT counter. Only INSERT statements and counters
// are taken from the export; the old structure is ignored (the v2 schema is created from
// database/schema_v2.sql). Refuses to run if an INSERT has no column list, because then rows could
// land in the wrong columns.

import { readFileSync, writeFileSync } from "node:fs";

const [, , input, output = "import_old_data.sql"] = process.argv;
if (!input) {
  console.error("Usage: node scripts/make-import-from-dump.mjs <old-export.sql> [out.sql]");
  process.exit(1);
}

const text = readFileSync(input, "utf8").replace(/^﻿/, "").replace(/\r\n/g, "\n");

const inserts = [...text.matchAll(/^INSERT INTO `(\w+)` (\(`[^\n]*?\)) VALUES\n[\s\S]*?\);\n/gm)];
const allInsertHeads = [...text.matchAll(/^INSERT INTO `(\w+)`/gm)].length;
if (inserts.length !== allInsertHeads) {
  console.error(`Found ${allInsertHeads} INSERT statements but only ${inserts.length} have a column list.`);
  console.error("Re-export from phpMyAdmin with 'Complete inserts' ticked (Custom export > Data creation options).");
  process.exit(2);
}

const counters = [...text.matchAll(/ALTER TABLE `(\w+)`\n\s+MODIFY `\w+`[^\n]*AUTO_INCREMENT, AUTO_INCREMENT=(\d+);/g)];

const rowCount = (block) => (block.match(/^\(/gm) || []).length;
const lines = [];
lines.push("-- Data-only import generated by scripts/make-import-from-dump.mjs");
lines.push(`-- Source: ${input}`);
lines.push("-- Run on a database created from schema_v2.sql, with nothing else in it.");
lines.push("");
lines.push('SET NAMES utf8mb4;');
lines.push('SET time_zone = "+00:00";');
lines.push('SET SQL_MODE = "NO_AUTO_VALUE_ON_ZERO";');
lines.push("SET FOREIGN_KEY_CHECKS = 0;");
lines.push("START TRANSACTION;");
lines.push("");

const summary = [];
for (const m of inserts) {
  lines.push(m[0].trimEnd());
  lines.push("");
  summary.push(`${m[1]}=${rowCount(m[0])}`);
}

lines.push("COMMIT;");
lines.push("");
lines.push("-- Keep the next-id counters exactly where the old database had them (ids that were deleted stay unused).");
for (const c of counters) lines.push(`ALTER TABLE \`${c[1]}\` AUTO_INCREMENT = ${c[2]};`);
lines.push("");
lines.push("SET FOREIGN_KEY_CHECKS = 1;");
lines.push("");

writeFileSync(output, lines.join("\n"), "utf8");
console.log(`Wrote ${output}`);
console.log(`Tables with data: ${inserts.length}; counters preserved: ${counters.length}`);
console.log(summary.join("  "));
