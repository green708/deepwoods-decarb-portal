export type ColType = "text" | "number" | "select" | "date";

export interface ColDef {
  key: string;
  label: string;
  type: ColType;
  unit?: string;
  options?: string[];
  required?: boolean;
  helper?: string;
}

export interface SubTableDef {
  title: string;
  columns: ColDef[];
  exampleRow?: Record<string, string>;
}

export interface MethodDef {
  id: string;
  label: string;
  helper?: string;
  columns: ColDef[];
  subtables?: SubTableDef[];
  warnings?: string[];
  emoji?: string;
  plainLabel?: string;
  plainDesc?: string;
  accuracy?: "best" | "good" | "fallback";
  accuracyLabel?: string;
  exampleRow?: Record<string, string>;
}

